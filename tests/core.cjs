const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),zlib=require('zlib'),path=require('path');
const root=path.resolve(__dirname,'..');
const box={console,PropertiesService:{getScriptProperties:()=>({getProperty:()=>null})},ScriptApp:{getService:()=>({getUrl:()=>''})},Utilities:{base64Decode:s=>Buffer.from(s,'base64'),newBlob:b=>({data:b}),ungzip:b=>({getDataAsString:()=>zlib.gunzipSync(b.data).toString()})}};
vm.createContext(box);
for(const name of ['Code.gs','StreetGeneration102.gs','PhotoAdapters.gs'])vm.runInContext(fs.readFileSync(path.join(root,'build',name),'utf8'),box,{filename:name});
const api=vm.runInContext('({Spatial,Chronology,ArchiveFilter,HistoryQuery})',box);
const read=n=>JSON.parse(fs.readFileSync(path.join(root,'data/example',n+'.json')));
const spatial=read('spatial'),timeline=read('timeline'),archive=read('archive');
const rows=api.Spatial.enrich(archive.records,spatial);
assert.equal(rows[0].spatial.uncertainty_m,100);
assert.equal(api.Spatial.enrich([{...archive.records[0],location_unresolved:true}],spatial)[0].spatial,null);
assert.equal(api.Chronology.state(spatial.buildings[0],1900,timeline).status,'not-built');
assert.equal(api.Chronology.state(spatial.buildings[0],1921,timeline).status,'documented');
assert.equal(api.Chronology.state(spatial.buildings[0],1922,timeline).status,'continuity');
assert.equal(api.HistoryQuery.resolve('What happened at 3143 Cass in 1921?',1970).year,1921);
assert.equal(api.HistoryQuery.resolve('Compare 1921 and 1950',1970).code,'MULTIPLE_YEARS');
assert.equal(api.Spatial.photoDate({date:'Unknown'},1921),false);
assert.equal(api.Spatial.photoDate({date:'1921–1925'},1922),true);
const geo=api.Spatial.geographic(api.Spatial.local([-83.059,42.3372],[-83.05,42.33]),[-83.05,42.33]);
assert(Math.abs(geo[0]+83.059)<1e-8&&Math.abs(geo[1]-42.3372)<1e-8);
assert.equal(box.archiveSeed_().records[0].id,'example-source-001');
assert.equal(box.spatialData_().buildings[0].id,'example-envelope');
assert.equal(box.timelineData_().buildings[0].envelopeIds[0],'example-envelope');
assert(box.streetPage102_().includes('Teaching fixture'));
assert.equal(box.getRound59Image_('anything').code,'NOT_INCLUDED');
console.log('PASS: source/anchor/building joins, time states, uncertainty, date parsing, coordinate conversion and compiled data loaders.');
